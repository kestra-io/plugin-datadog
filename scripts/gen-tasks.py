#!/usr/bin/env python3
"""Write docs/TASKS.md: every task and trigger of the plugin, grouped by package, with its one-line purpose.
The list is read from the source (the @Schema title of each @Plugin class), so it cannot drift. Usage: gen-tasks.py [--source src/main/java] [--out docs/TASKS.md]"""
import argparse, collections, importlib.util, pathlib

HERE = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("assemble_docs", HERE / "assemble-docs.py")
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)

TITLES = {
    "api": "Any Datadog operation", "monitors": "Monitors", "downtimes": "Downtimes", "dashboards": "Dashboards", "slos": "Service level objectives",
    "synthetics": "Synthetic tests", "deployments": "Deployment gates and DORA", "incidents": "Incidents", "cases": "Cases", "oncall": "On-call paging",
    "statuspages": "Status pages", "logs": "Logs", "spans": "Spans (APM)", "rum": "Real user monitoring", "audit": "Audit trail", "civisibility": "CI visibility",
    "events": "Events", "metrics": "Metrics", "hosts": "Hosts", "usage": "Usage", "cost": "Cost", "ddsql": "DDSQL", "users": "Users", "teams": "Teams",
    "keys": "API and application keys", "security": "Security monitoring", "catalog": "Service catalog",
}
ap = argparse.ArgumentParser()
ap.add_argument("--source", default="src/main/java")
ap.add_argument("--out", default="docs/TASKS.md")
a = ap.parse_args()
groups = collections.OrderedDict()
for cls, purpose in mod.task_rows(a.source):
    pkg, name = cls.split(".")[-2], cls.split(".")[-1]
    groups.setdefault(pkg, []).append((name, purpose))
out = ["# Tasks and triggers", "", f"{sum(len(v) for v in groups.values())} components in {len(groups)} packages. Generated by `scripts/gen-tasks.py` from the source. Each task page in Kestra has the properties, outputs and full flow examples.", ""]
for pkg in sorted(groups, key=lambda p: TITLES.get(p, p).lower()):
    out += [f"## {TITLES.get(pkg, pkg.title())} (`{pkg}`)", ""]
    out += [f"- `{pkg}.{n}`: {p}" for n, p in sorted(groups[pkg])]
    out.append("")
pathlib.Path(a.out).write_text("\n".join(out))
print(f"wrote {a.out}: {sum(len(v) for v in groups.values())} components")
