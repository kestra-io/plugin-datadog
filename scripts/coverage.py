#!/usr/bin/env python3
"""Generate measured API reach and typed-task coverage from the pinned specs."""
import argparse
import json
import re
from collections import Counter
from pathlib import Path

from spec_tools import load, operations, typed_operations


def contract_adoption(source):
    """Count test classes with executable helper assertions, excluding helper tests."""
    adopted = []
    for file in sorted(Path(source).rglob("*Test.java")):
        if file.parent.name in {"contract", "api", "e2e"}:
            continue
        text = re.sub(r"/\*.*?\*/|//[^\n]*", "", file.read_text(), flags=re.S)
        if re.search(r"OpenApiContract\.(?:assertRequests\s*\(|of\s*\([^;]+\.assert(?:Request|Response)\s*\()", text):
            adopted.append(str(file.relative_to(source).with_suffix("")).replace("/", "."))
    return adopted


def report(rows, typed, legacy, unresolved, schemas, sources, adoption=()):
    total = Counter(row["tag"] for row in rows.values())
    covered = Counter(rows[key]["tag"] for key in typed)
    typed_components = {task for tasks in typed.values() for task in tasks}
    lines = ["# Datadog API coverage", "", "Generated by `scripts/coverage.py`. Counts are version-qualified operations, not task classes.", "",
             f"Operations in the supplied specs: **{len(rows)}**. Operations mapped to typed tasks: **{len(typed)}**. Generic-only operations: **{len(rows) - len(typed)}**.", "",
             f"Mapped typed components: **{len(typed_components)}**, including polling triggers. Generic helpers are excluded from this component count.", "",
             "Every listed operation is represented by the catalog used by `api.Call`. This is routing reach, not live API verification.", "",
             f"Vendored contract schemas: **{len(schemas)}**. A vendored schema is not proof that every test uses the contract helper.", "",
             f"Typed-task test classes asserting through OpenApiContract: **{len(adoption)}** (baseline: **7**). Counted from executable assertions in test source, excluding generic API and helper self-tests.", "",
             "Contract adopters: " + ", ".join(f"`{name}`" for name in adoption) + ".", "", "## Source digests", ""]
    lines.extend(f"- {source['api']}: `{source['sha256']}`" for source in sources)
    lines += ["", "## Totals by tag", "", "| Tag | Operations | Typed | Generic only |", "|---|---:|---:|---:|"]
    lines.extend(f"| {tag} | {total[tag]} | {covered[tag]} | {total[tag] - covered[tag]} |" for tag in sorted(total))
    lines += ["", "## Mapping method", "", "New mappings come from `operationId` references in task Javadoc. Duplicate IDs require a version prefix or an exact API path in the source."]
    if legacy:
        lines += ["", "The base tasks predate those tags. These explicit legacy mappings are maintained in `scripts/spec_tools.py`: " + ", ".join(f"`{task}`" for task in legacy) + "."]
    if unresolved:
        lines += ["", "Tasks without a resolvable operationId tag: " + ", ".join(f"`{task}`" for task in unresolved) + ". They are not counted as typed coverage."]
    lines += ["", "## Every operation", "", "| Qualified operationId | Tag | Method and path | Typed tasks | Contract schema |", "|---|---|---|---|---|"]
    for key, row in sorted(rows.items()):
        tasks = ", ".join(f"`{task}`" for task in sorted(typed.get(key, []))) or "`api.Call` only"
        schema = f"`{schemas[key]}`" if key in schemas else "-"
        lines.append(f"| `{key}` | {row['tag']} | `{row['method']} {row['path']}` | {tasks} | {schema} |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("v1", type=Path); parser.add_argument("v2", type=Path)
    parser.add_argument("--source", type=Path, default=Path("src/main/java/io/kestra/plugin/datadog"))
    parser.add_argument("--schemas", type=Path, default=Path("src/test/resources/openapi/index.json"))
    parser.add_argument("--output", type=Path, default=Path("docs/COVERAGE.md"))
    parser.add_argument("--tests", type=Path, default=Path("src/test/java/io/kestra/plugin/datadog"))
    args = parser.parse_args()
    docs, sources = load([args.v1, args.v2]); rows = operations(docs)
    typed, legacy, unresolved = typed_operations(args.source, rows)
    schemas = json.loads(args.schemas.read_text()) if args.schemas.exists() else {}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    adoption = contract_adoption(args.tests)
    args.output.write_text(report(rows, typed, legacy, unresolved, schemas, sources, adoption))
    print(f"{len(rows)} operations; {len(typed)} typed; {len(rows) - len(typed)} generic only; {len(schemas)} schemas; {len(unresolved)} unmapped tasks")
    print(f"{len(adoption)} typed-task test classes use contract assertions")


if __name__ == "__main__":
    main()
